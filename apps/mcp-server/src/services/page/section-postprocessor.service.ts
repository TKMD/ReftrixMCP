/**
 * Section Merge Post-Processor
 *
 * JSDOM ベースのセクション検出で発生する過剰分割を、ルールベースのポストプロセッサで修正する。
 * Phase 1 (Layout Analysis) 内、mergeVisionDetectedSections() 後、DB保存前に実行される。
 *
 * Fixes over-segmentation from JSDOM-based section detection via rule-based post-processing.
 * Runs in Phase 1 (Layout Analysis) after mergeVisionDetectedSections(), before DB save.
 *
 * ルール（実行順序） / Rules (execution order):
 * - Rule 4: 巨大セクション再分割（height > 10,000px → 3戦略で再分割）
 *           Large section split (height > 10,000px → split via 3 strategies)
 * - Rule 1: 同一タイプ連続マージ（3+連続の同一タイプセクション → 1つに統合）
 *           Consecutive same-type merge (3+ consecutive same-type sections → 1)
 * - Rule 3: 同名隣接マージ（同一タイプ+同名の2+連続セクション → 1つに統合）
 *           Same-heading adjacent merge (same type + same heading, 2+ consecutive → 1)
 * - Rule 2: コンテンツ空セクション吸収（heading無し+textContent<20文字 → 隣接に吸収）
 *           Empty-content section absorption (no heading + textContent<20 chars → absorb into neighbor)
 *
 * PII: PII分類はPhase 5で実施。このフェーズではPIIフィルタリング不要。
 * PII: PII classification is performed in Phase 5. No PII filtering needed in this phase.
 *
 * @module services/page/section-postprocessor
 */

import { isDevelopment, logger } from "../../utils/logger";

// =====================================================
// 定数 / Constants
// =====================================================

/**
 * 同一タイプ連続マージの最小連続数
 * Minimum consecutive count for same-type merge
 */
const MIN_CONSECUTIVE_COUNT = 3;

/**
 * マージ対象のセクションタイプ（構造的に繰り返しが多いタイプ）
 * navigation/hero/footer は個別に意味があるためマージ対象外
 * cta はv0.1.8でマージ対象に変更（3+連続CTAの過剰分割が実データで確認されたため）
 *
 * Section types eligible for merge (types that commonly repeat structurally).
 * navigation/hero/footer are excluded as they have individual significance.
 * cta was added in v0.1.8 (3+ consecutive CTA over-segmentation confirmed in production data).
 */
const MERGEABLE_TYPES = new Set([
  "unknown",
  "feature",
  "testimonial",
  "gallery",
  "partners",
  "portfolio",
  "team",
  "stories",
  "stats",
  "faq",
  "cta",
]);

/**
 * 同名隣接マージの最小連続数（Rule 3用）
 * Minimum consecutive count for same-heading adjacent merge (Rule 3)
 */
const MIN_SAME_HEADING_COUNT = 2;

/**
 * textContent空判定の閾値（文字数）
 * Threshold for textContent empty detection (character count)
 */
const TEXT_CONTENT_EMPTY_THRESHOLD = 20;

/**
 * 入力セクション数の安全上限
 * Maximum input section count safety limit
 */
const MAX_INPUT_SECTIONS = 500;

/**
 * 巨大セクション再分割閾値（px）
 * Large section split threshold (px)
 *
 * TDA MEDIUM-4: 10,000px は DINOv2 ViT-B/14 の入力解像度 224x224 に対して
 * アスペクト比が極端になり visual embedding 品質が劣化する閾値。
 * 一般的なビューポート高さ（900px）の約11倍に相当し、
 * 実データ（supabase.com等）で 10,000px 超セクションの embedding 類似度低下が確認されたため設定。
 *
 * TDA MEDIUM-4: 10,000px is the threshold where aspect ratio becomes extreme
 * relative to DINOv2 ViT-B/14 input resolution (224x224), degrading visual embedding quality.
 * Equals ~11x typical viewport height (900px). Confirmed embedding similarity degradation
 * for sections exceeding 10,000px in production data (e.g., supabase.com).
 */
const MAX_SECTION_HEIGHT = 10_000;

/**
 * 分割後の最小高さ（px）
 * Minimum height after split (px)
 */
const MIN_SPLIT_SECTION_HEIGHT = 1_000;

/**
 * 1セクションからの最大分割数
 * Maximum splits per section
 */
const MAX_SPLIT_COUNT = 20;

/**
 * 巨大セクション再分割の Feature flag（ランタイム評価）
 * Feature flag for large section split (runtime evaluation)
 */
function isSectionSplitEnabled(): boolean {
  return process.env["ENABLE_SECTION_SPLIT_POSTPROCESSOR"] !== "false";
}

