// ============================================================================

/**
 * Generate a truncated report ID for use in audit emit `details.truncatedReportId`
 * and as the targetId for audit_logs PII-safety binding. Per Δ11, the format
 * is `report.<truncatedTs>.<seqOnly>` where:
 *   - `truncatedTs` = `floor(unix_timestamp_seconds / 60) * 60` (1-min bucket)
 *   - `seqOnly` = process-local monotonic sequence (no pid)
 *
 * The targetId is then PII-truncated to `AUDIT_LOG_CONSTANTS.TARGET_ID_TRUNCATE_LENGTH`
 * via the SSOT `truncateAuditTargetId` helper.
 */
let processLocalSeq = 0;
export function generateTruncatedReportId(now: Date = new Date()): string {
  const unixSec = Math.floor(now.getTime() / 1000);
  const bucketSec = Math.floor(unixSec / 60) * 60;
  const seq = ++processLocalSeq;
  return `report.${bucketSec}.${seq}`;
}

/** Test-only: reset process-local sequence so deterministic IDs can be asserted. */
export function resetSequenceForTesting(): void {
  processLocalSeq = 0;
}

/**
 * Build the audit-log-safe target ID for a crash report. Combines
 * {@link generateTruncatedReportId} with SSOT
 * {@link truncateAuditTargetId} (= 8 chars + "..." per
 * `AUDIT_LOG_CONSTANTS.TARGET_ID_TRUNCATE_LENGTH`).
 */
export function buildAuditTargetIdForReport(truncatedReportId: string): string | null {
  return truncateAuditTargetId(truncatedReportId);
}
