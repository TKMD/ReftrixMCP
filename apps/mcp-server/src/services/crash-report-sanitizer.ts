/**
 * Result of {@link sanitizeReport}. `sanitizationApplied=true` indicates the
 * happy path; `false` indicates a sanitiser exception triggered the fail-open
 * fallback (SLO marker + audit emit Δ2 #6 + Δ5 Metric A).
 */
export interface CrashReportSanitizationResult {
  report: unknown;
  sanitizationApplied: boolean;
  sanitizationDurationMs: number;
  /** Top JS frame summary (sanitised), useful for audit emit. */
  jsStackTopFrame: string | null;
  /** Top native frame symbol (after Δ9 stripping), useful for audit emit. */
  nativeStackTopSymbol: string | null;
}

// ============================================================================
// Core sanitisation helpers (pure functions, deterministic)
// ============================================================================

/**
 * Strip non-public native symbols (`__libc_*` / `vips_internal_*`) per V1 Δ9.
 * Public APIs are preserved. Returns the original symbol if not internal.
 *
 * @example
 *   stripNonPublicNativeSymbols("__libc_malloc") === "[REDACTED-NATIVE-INTERNAL]"
 *   stripNonPublicNativeSymbols("vips_internal_buffer") === "[REDACTED-NATIVE-INTERNAL]"
 *   stripNonPublicNativeSymbols("ONNXSession::Run") === "ONNXSession::Run"
 */
export function stripNonPublicNativeSymbols(symbol: string): string {
  if (typeof symbol !== "string" || symbol.length === 0) return symbol;
  if (NATIVE_INTERNAL_PREFIX_REGEX.test(symbol)) {
    return REDACTED_NATIVE_INTERNAL;
  }
  return symbol;
}

/**
 * Sanitise an argv element: redact URLs, UUIDs, and otherwise pass-through.
 * Used by {@link sanitizeArgv}.
 */
export function sanitizeArgvElement(arg: string): string {
  if (typeof arg !== "string" || arg.length === 0) return arg;
  // Order matters: URL first (it may contain a UUID), then UUID, then keep.
  let result = arg;
  if (URL_REGEX.test(result)) {
    URL_REGEX.lastIndex = 0;
    result = result.replace(URL_REGEX, REDACTED_URL);
  }
  if (UUID_REGEX.test(result)) {
    UUID_REGEX.lastIndex = 0;
    result = result.replace(UUID_REGEX, REDACTED_UUID);
  }
  return result;
}

/**
 * Sanitise the argv array. Returns a new array; does not mutate input.
 *
 * Per V1 §7.1 unit test #1 + Δ2 #2 / #3:
 *   - `https://example.com/page` → `[REDACTED-URL]`
 *   - UUIDv4/v7 boot token → `[REDACTED-UUID]`
 *   - `--page` / `--backfill` CLI flags preserved
 */
export function sanitizeArgv(argv: readonly string[]): string[] {
  if (!Array.isArray(argv)) return [];
  return argv.map(sanitizeArgvElement);
}

/**
 * Sanitise the environment variables object. Returns a new object; does not
 * mutate input. Per V1 §4.3 SSOT pattern — uses `AUDIT_SENSITIVE_KEYS` from
 * the audit-log SSOT directly (V1 §4.3 forbidden patterns: private
 * re-declaration would fail INV-AUDIT-EMIT-SSOT-IMPORT-001 AST scan).
 *
 * Per V1 §7.1 unit test #2 + Δ2 #1:
 *   - `DATABASE_URL` / `REDIS_PASSWORD` / `OPENAI_API_KEY` → `[REDACTED]`
 *     (matched against `AUDIT_SENSITIVE_KEYS` set, case-insensitive
 *     substring per the existing `audit-log.service` semantics — keys
 *     literally containing `password`/`token`/`secret`/`apiKey`/etc.)
 *   - Reftrix `NODE_ENV` / `PORT` / `REFTRIX_*` preserved
 *
 * **Sensitivity check semantics**: The SSOT `AUDIT_SENSITIVE_KEYS` set
 * contains exact literal keys plus the commonly-used variants. For Node.js
 * environment-variable redaction we additionally apply a case-insensitive
 * substring match against well-known PII fragments (`password`, `secret`,
 * `token`, `apiKey`, `api_key`, `accessToken`, `access_token`,
 * `refreshToken`, `refresh_token`, `authorization`, `cookie`, `session`,
 * `credential`, `private_key`, `privateKey`, `databaseUrl`, `database_url`).
 * The substring sensitivity expansion is JUSTIFIED here because env-var
 * conventions (e.g., `MY_DATABASE_URL`, `OPENAI_API_KEY`, `STRIPE_SECRET_KEY`)
 * embed PII fragments in concatenated keys. Without expansion, only literal
 * `apiKey` / `api_key` would be caught, leaking `MY_API_KEY`. The set itself
 * remains SSOT-imported; only the matching predicate is expanded.
 */
export function sanitizeEnv(env: Record<string, string | undefined>): Record<string, string> {
  if (!env || typeof env !== "object") return {};
  const result: Record<string, string> = {};
  for (const [key, value] of Object.entries(env)) {
    if (value === undefined) continue;
    if (isSensitiveEnvKey(key)) {
      result[key] = REDACTED_VALUE;
    } else {
      // Defense-in-depth: also strip embedded connection URLs from
      // ostensibly-safe env values (e.g., `PATH` contains nothing sensitive
      // but a third-party tool could surface a connection string).
      result[key] = stripConnectionUrls(value);
    }
  }
  return result;
}

/**
 * Test whether an env var name matches the SSOT sensitive-key allowlist.
 * Combines exact-set membership with case-insensitive substring match for
 * common PII fragments embedded in concatenated env names (e.g.,
 * `MY_DATABASE_URL`, `STRIPE_SECRET_KEY`).
 */
function isSensitiveEnvKey(key: string): boolean {
  if (AUDIT_SENSITIVE_KEYS.has(key)) return true;
  const lower = key.toLowerCase();
  for (const sensitiveKey of AUDIT_SENSITIVE_KEYS) {
    if (lower.includes(sensitiveKey.toLowerCase())) return true;
  }
  // Additional well-known fragments not in AUDIT_SENSITIVE_KEYS but
  // semantically equivalent (database URL is the most prominent example —
  // not in the audit-log SSOT because audit_logs.details rarely carries
  // raw env values, but env redaction MUST cover it).
  if (
    lower.includes("database_url") ||
    lower.includes("databaseurl") ||
    lower.includes("redis_url") ||
    lower.includes("redisurl")
  ) {
    return true;
  }
  return false;
}

/** Strip embedded connection URLs (postgres:// / redis:// / etc.) from a value. */
export function stripConnectionUrls(value: string): string {
  if (typeof value !== "string" || value.length === 0) return value;
  CONNECTION_URL_REGEX.lastIndex = 0;
  if (!CONNECTION_URL_REGEX.test(value)) return value;
  CONNECTION_URL_REGEX.lastIndex = 0;
  return value.replace(CONNECTION_URL_REGEX, REDACTED_URL);
}

/**
 * Normalise a JS stack frame file path. Repo-internal paths are converted
 * to relative form (`apps/mcp-server/...`); external paths are redacted.
 *
 * Per V1 §7.1 unit test #4 + Δ2 #4:
 *   - `/home/user/.../Reftrix/apps/mcp-server/src/x.ts` →
 *     `apps/mcp-server/src/x.ts`
 *   - `/home/user/.../secret.json` (outside repo) → `[REDACTED-NON-REPO-PATH]`
 */
export function normaliseStackFramePath(framePath: string): string {
  if (typeof framePath !== "string" || framePath.length === 0) return framePath;
  // Built-in modules (no path separator) — pass through.
  if (!framePath.includes("/") && !framePath.includes("\\")) return framePath;
  let resolved: string;
  try {
    resolved = path.resolve(framePath);
  } catch {
    return REDACTED_NON_REPO_PATH;
  }
  const repoRoot = resolveRepoRoot();
  if (resolved.startsWith(repoRoot + path.sep) || resolved === repoRoot) {
    const relative = path.relative(repoRoot, resolved);
    // Always use POSIX-style separators in the sanitised output for
    // platform-independent assertions.
    return relative.split(path.sep).join("/");
  }
  return REDACTED_NON_REPO_PATH;
}

/**
 * Walk a string field for embedded URLs (`https?://`) and connection URLs
 * (`postgres://`, `redis://`, etc.). Used by the heap-string defense (Δ2 #5).
 */
export function sanitizeHeapString(value: string): string {
  if (typeof value !== "string" || value.length === 0) return value;
  let result = stripConnectionUrls(value);
  URL_REGEX.lastIndex = 0;
  if (URL_REGEX.test(result)) {
    URL_REGEX.lastIndex = 0;
    result = result.replace(URL_REGEX, REDACTED_URL);
  }
  UUID_REGEX.lastIndex = 0;
  if (UUID_REGEX.test(result)) {
    UUID_REGEX.lastIndex = 0;
    result = result.replace(UUID_REGEX, REDACTED_UUID);
  }
  return result;
}

