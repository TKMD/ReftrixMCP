/**
 * Crash Report Sanitizer — PII-safe normalization of Node.js `process.report`
 *
 * Wave 3 PR3a (Plan v3 T2 V1 §4.3 + Δ2 + Δ9). Sanitises raw diagnostic
 * reports emitted by `process.report` (Node.js 20+ built-in) before they are
 * persisted to public disk. Removes:
 *
 * 1. **Sensitive environment variables** (`AUDIT_SENSITIVE_KEYS` SSOT import
 *    from `audit-log.service.ts`) — `DATABASE_URL`, `REDIS_PASSWORD`, etc. →
 *    `[REDACTED]`
 * 2. **argv URLs** (https?:// → `[REDACTED-URL]`)
 * 3. **argv UUIDv4/v7 boot tokens** → `[REDACTED-UUID]`
 * 4. **JS stack frame file paths** outside the repo root →
 *    `[REDACTED-NON-REPO-PATH]`; repo-internal paths normalised to relative
 * 5. **Heap string fields containing `postgres://` / `redis://` URLs** → URL
 *    stripped (CWE-209 + GDPR Art.30)
 * 6. **Native stack non-public symbols** (`__libc_*` / `vips_internal_*`) →
 *    `[REDACTED-NATIVE-INTERNAL]` per Δ9 LCC + SEC sign-off
 *
 * **Fail-open contract** (Δ2 #6): if sanitisation throws, emit a
 * `[SLO_MARKER] crash_report_sanitize_failed` log line and return the
 * original report with `sanitizationApplied=false`. The audit emit downstream
 * triggers L1.5 SLO_MARKER and L3 CRIT (GDPR Art.33 escalate gate via Δ5
 * Metric A — `sanitizationApplied=false` events / 60-min window ≥ 1).
 *
 * **SSOT contract** (V1 §4.3 Δ2): MUST import all 3 symbols from
 * `audit-log.service.ts` — `AUDIT_LOG_CONSTANTS.TARGET_ID_TRUNCATE_LENGTH` /
 * `AUDIT_SENSITIVE_KEYS` / `truncateAuditTargetId`. The
 * INV-AUDIT-EMIT-SSOT-IMPORT-001 AST scan asserts this import path.
 *
 * **Hard prohibitions** (V1 §4.3 forbidden patterns):
 *   - `.slice(0, 8) + "..."` hardcoded literal
 *   - private re-declaration of `SENSITIVE_KEYS`
 *   - any non-imported truncation length constant
 *
 * @module services/crash-report-sanitizer
 * @see Plan v3 T2 V1 §4.3 / Δ2 / Δ9 / §13.1 SEC sign-off evidence #2
 * @see ADR-0021 §"Privacy Considerations" / §"Native Stack Symbol Stripping"
 * @see INV-WORKER-CRASH-DUMP-001 PII-leak-fail-closed standing regression
 * @see INV-AUDIT-EMIT-SSOT-IMPORT-001 SSOT binding standing regression
 */

