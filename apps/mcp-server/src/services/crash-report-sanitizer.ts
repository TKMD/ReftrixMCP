export { AUDIT_LOG_CONSTANTS, AUDIT_SENSITIVE_KEYS, truncateAuditTargetId };

// ============================================================================
// Redaction tokens — fixed strings (PII-safe by construction)
// ============================================================================

export const REDACTED_VALUE = "[REDACTED]";
export const REDACTED_URL = "[REDACTED-URL]";
export const REDACTED_UUID = "[REDACTED-UUID]";
export const REDACTED_NON_REPO_PATH = "[REDACTED-NON-REPO-PATH]";
export const REDACTED_NATIVE_INTERNAL = "[REDACTED-NATIVE-INTERNAL]";

/** SLO marker emitted on fail-open path (Δ2 #6 + Δ5 Metric A trigger). */
export const SLO_MARKER_SANITIZE_FAILED = "[SLO_MARKER] crash_report_sanitize_failed";

// ============================================================================
// Regex sources (compiled lazily; readonly at module level)
// ============================================================================

/** Match http:// or https:// URLs (used for argv + heap string redaction). */
const URL_REGEX = /https?:\/\/[^\s"']+/g;

/**
 * Match canonical UUID v4 / v7 forms (8-4-4-4-12 hex, optional version
 * specifier in the 3rd group). Boot tokens generated by `randomUUID()` are
 * v4; per-type tokens generated by internal / Reftrix are typically v7. Both
 * MUST be redacted before public disk write per SEC-V11-01 Rule 6 (boot token
 * log prohibition extended to crash dump body).
 */
const UUID_REGEX = /\b[0-9a-f]{8}-[0-9a-f]{4}-[1-7][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\b/gi;

/**
 * Match DB / cache connection URLs (postgres://, redis://, mongodb://, etc.)
 * embedded in arbitrary string fields. Heap snapshots from `process.report`
 * may contain serialised connection strings; CWE-209 + GDPR Art.30 require
 * stripping before retention.
 */
const CONNECTION_URL_REGEX =
  /\b(?:postgres|postgresql|redis|rediss|mongodb|mongodb\+srv|mysql|amqp|amqps):\/\/[^\s"']+/gi;

/**
 * Match non-public native symbols (libc internals + vips internals). The
 * V1 spec Δ9 contract: replace `__libc_*` / `vips_internal_*` with
 * `[REDACTED-NATIVE-INTERNAL]`. Public APIs (`ONNXSession.run`, `abort`,
 * `Sharp::pipeline`) are preserved as-is.
 */
const NATIVE_INTERNAL_PREFIX_REGEX = /^(?:__libc_|vips_internal_)/;

// ============================================================================
// Repo-root detection (used for JS stack frame normalisation)
// ============================================================================

/**
 * Resolve the repository root for path normalisation. Cached at first call.
 * Defaults to `process.cwd()` if `REFTRIX_REPO_ROOT` env var is unset (test
 * harnesses may override via env to assert deterministic relative paths).
 */
let cachedRepoRoot: string | null = null;
function resolveRepoRoot(): string {
  if (cachedRepoRoot !== null) return cachedRepoRoot;
  const envRoot = process.env.REFTRIX_REPO_ROOT;
  cachedRepoRoot = envRoot && envRoot.length > 0 ? path.resolve(envRoot) : process.cwd();
  return cachedRepoRoot;
}

/** Test-only: reset cached repo root so a different env value can take effect. */
export function resetRepoRootCacheForTesting(): void {
  cachedRepoRoot = null;
}

// ============================================================================
// Sanitisation result shape
