/**
 * Sanitise a raw Node.js `process.report` object. Returns a new object; does
 * not mutate input. Returns a {@link CrashReportSanitizationResult} with
 * timing + observability metadata for the audit emit downstream.
 *
 * **Fail-open contract** (Δ2 #6): if any step throws, the original report is
 * returned with `sanitizationApplied=false` and a SLO marker is logged.
 * The downstream audit emit then triggers L1.5 SLO_MARKER and Δ5 Metric A
 * (GDPR Art.33 escalate gate via L3 CRIT).
 */
export function sanitizeReport(rawReport: unknown): CrashReportSanitizationResult {
  const startTime = Date.now();
  // Defensive copy + sanitisation in a single try-block. The fail-open
  // contract requires we return the ORIGINAL report (untouched) if any
  // throw occurs, so we keep `rawReport` aside and operate on a clone.
  try {
    if (rawReport === null || typeof rawReport !== "object") {
      // Non-object input — pass through but mark sanitised (nothing to redact).
      return {
        report: rawReport,
        sanitizationApplied: true,
        sanitizationDurationMs: Date.now() - startTime,
        jsStackTopFrame: null,
        nativeStackTopSymbol: null,
      };
    }
    const cloned = JSON.parse(JSON.stringify(rawReport)) as Record<string, unknown>;
    const sanitisedReport = sanitiseReportInternal(cloned);
    const jsStackTopFrame = extractJsStackTopFrame(sanitisedReport);
    const nativeStackTopSymbol = extractNativeStackTopSymbol(sanitisedReport);
    return {
      report: sanitisedReport,
      sanitizationApplied: true,
      sanitizationDurationMs: Date.now() - startTime,
      jsStackTopFrame,
      nativeStackTopSymbol,
    };
  } catch (error) {
    // Fail-open: emit SLO marker, return original report, downstream audit
    // emit will set sanitizationApplied=false → Δ5 Metric A trigger.
    logger.warn(SLO_MARKER_SANITIZE_FAILED, {
      errorMessage: error instanceof Error ? error.message : "unknown",
    });
    return {
      report: rawReport,
      sanitizationApplied: false,
      sanitizationDurationMs: Date.now() - startTime,
      jsStackTopFrame: null,
      nativeStackTopSymbol: null,
    };
  }
}

/**
 * Recursive sanitisation walker for the cloned report tree. Internal — must
 * stay total over arbitrary `process.report` shape (Node version drift
 * tolerant). Keys present in `process.report` v12+ stable shape:
 *   - `header.commandLine` (argv array)
 *   - `environmentVariables` (object)
 *   - `javascriptStack.stack` (array of frame strings)
 *   - `nativeStack` (array of symbol strings)
 *   - `javascriptHeap` (object containing arbitrary heap fields)
 *   - `libuv` / `workers` / `userLimits` / `sharedObjects` (less PII-prone)
 *
 * For unknown keys we recursively walk and apply heap-string sanitisation to
 * any string leaf. This is defensive against future Node versions adding new
 * keys (R4 mitigation).
 *
 * **Wave 4 SRP refactor (TDA M-1 c, 2026-05-11)**: split the inline 5-section
 * body into 5 named sub-functions, each with CC ≤ 5, matching the Wave 1
 * T3-Vision precedent. Behaviour-preserving — 39 sanitizer + 7 PII safety
 * unit tests + 1 PII leak fail-closed standing all continue to pass post-
 * refactor. The orchestrator below now has CC = 1 (5 linear delegations).
 *
 * @see Wave 4 Finding Registry TDA M-1 c (CC>10 SRP refactor)
 */
function sanitiseReportInternal(obj: Record<string, unknown>): Record<string, unknown> {
  // Each sub-function is a no-op when its section is missing / mistyped, so
  // the orchestrator can stay linear (CC = 1) over the 5 sections.
  sanitiseHeader(obj);
  sanitiseEnvironmentVariables(obj);
  sanitiseJavascriptStack(obj);
  sanitiseNativeStack(obj);
  sanitiseJavascriptHeap(obj);
  return obj;
}

/**
 * Section 1 — `header.commandLine` argv + `header.cwd` path normalisation.
 *
 * No-op when `obj.header` is absent or not an object. Mutates `obj.header`
 * in place when present.
 *
 * Cyclomatic complexity ≤ 5 (3 type guards + linear assignments).
 */
function sanitiseHeader(obj: Record<string, unknown>): void {
  if (!obj.header || typeof obj.header !== "object") return;
  const header = obj.header as Record<string, unknown>;
  if (Array.isArray(header.commandLine)) {
    header.commandLine = sanitizeArgv(header.commandLine as readonly string[]);
  }
  // `cwd` / `host` may surface usernames — redact if outside repo root.
  if (typeof header.cwd === "string") {
    header.cwd = normaliseStackFramePath(header.cwd);
  }
}

/**
 * Section 2 — `environmentVariables` AUDIT_SENSITIVE_KEYS SSOT + case-
 * insensitive substring match.
 *
 * Cyclomatic complexity ≤ 5 (1 type guard + 1 assignment).
 */
function sanitiseEnvironmentVariables(obj: Record<string, unknown>): void {
  if (!obj.environmentVariables || typeof obj.environmentVariables !== "object") return;
  obj.environmentVariables = sanitizeEnv(
    obj.environmentVariables as Record<string, string | undefined>
  );
}

/**
 * Section 3 — `javascriptStack.stack` frame array + `javascriptStack.message`
 * heap-string sanitisation.
 *
 * Cyclomatic complexity ≤ 5 (3 type guards + 1 map callback with 1 guard).
 */
function sanitiseJavascriptStack(obj: Record<string, unknown>): void {
  if (!obj.javascriptStack || typeof obj.javascriptStack !== "object") return;
  const jsStack = obj.javascriptStack as Record<string, unknown>;
  if (Array.isArray(jsStack.stack)) {
    jsStack.stack = (jsStack.stack as unknown[]).map((frame) => {
      if (typeof frame !== "string") return frame;
      return sanitiseStackFrameLine(frame);
    });
  }
  if (typeof jsStack.message === "string") {
    jsStack.message = sanitizeHeapString(jsStack.message);
  }
}

/**
 * Section 4 — `nativeStack` symbol stripping (native internal prefix + file
 * path normalisation).
 *
 * Map callback CC ≤ 5 (3 guard branches + 1 fall-through return). The
 * outer function delegates entirely to the map.
 */
function sanitiseNativeStack(obj: Record<string, unknown>): void {
  if (!Array.isArray(obj.nativeStack)) return;
  obj.nativeStack = (obj.nativeStack as unknown[]).map((entry) => sanitiseNativeStackEntry(entry));
}

/**
 * Section 4 helper — sanitise a single `nativeStack` entry.
 *
 * Entries may be: (a) plain symbol strings, (b) `{ symbol: string }` objects,
 * or (c) any other shape (passed through unchanged).
 *
 * Cyclomatic complexity ≤ 5 (3 branches + 1 default).
 */
function sanitiseNativeStackEntry(entry: unknown): unknown {
  if (typeof entry === "string") return stripNonPublicNativeSymbols(entry);
  if (entry && typeof entry === "object") {
    const e = entry as Record<string, unknown>;
    if (typeof e.symbol === "string") e.symbol = stripNonPublicNativeSymbols(e.symbol);
    return e;
  }
  return entry;
}

/**
 * Section 5 — `javascriptHeap` heap-string PII strip (Δ2 #5).
 *
 * Cyclomatic complexity ≤ 5 (1 type guard + 1 assignment).
 */
function sanitiseJavascriptHeap(obj: Record<string, unknown>): void {
  if (!obj.javascriptHeap || typeof obj.javascriptHeap !== "object") return;
  obj.javascriptHeap = sanitiseHeapObject(obj.javascriptHeap as Record<string, unknown>);
}

/**
 * Sanitise a JS stack frame line. Node.js stack frames have the shape:
 *   `at FunctionName (/path/to/file.ts:line:col)`
 * We extract the path between the parens and run it through
 * {@link normaliseStackFramePath}. If no parens are present, fall back to
 * heap-string sanitisation on the whole line.
 */
function sanitiseStackFrameLine(frame: string): string {
  const parenMatch = frame.match(/^(.*?\()(.+?)(:\d+:\d+\)?)$/);
  if (parenMatch !== null && parenMatch.length >= 4) {
    const prefix = parenMatch[1] ?? "";
    const filePath = parenMatch[2] ?? "";
    const suffix = parenMatch[3] ?? "";
    return prefix + normaliseStackFramePath(filePath) + suffix;
  }
  // No parens — pass through heap-string sanitisation (URL + UUID redaction).
  return sanitizeHeapString(frame);
}

/**
 * Recursively sanitise a heap object: for every string leaf, apply
 * {@link sanitizeHeapString}; for every nested object, recurse; for every
 * key matching `AUDIT_SENSITIVE_KEYS`, redact to `[REDACTED]`.
 *
 * **Wave 4 SRP refactor (TDA V1-04 c, 2026-05-11)**: split the inline body
 * (previously CC=12) into 3 named sub-functions, each with CC ≤ 5:
 *   - {@link sanitiseHeapObject} (orchestrator): CC = 3 (depth guard + for + 1 redacted-key branch)
 *   - {@link sanitiseHeapValue}: CC = 5 (string / array / object / primitive dispatch)
 *   - {@link sanitiseHeapArrayItem}: CC = 4 (string / object / primitive dispatch)
 *
 * Behaviour-preserving — 39 sanitizer + 7 PII safety unit tests + 1 PII leak
 * fail-closed standing regression all continue to pass post-refactor.
 *
 * @see Wave 4 Finding Registry TDA V1-04 c (sanitiseHeapObject CC=12 refactor)
 */
function sanitiseHeapObject(
  obj: Record<string, unknown>,
  depth: number = 0
): Record<string, unknown> {
  // Bounded recursion (defense against malformed circular refs after clone).
  if (depth > 64) return obj;
  const result: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(obj)) {
    if (AUDIT_SENSITIVE_KEYS.has(key) || isSensitiveEnvKey(key)) {
      result[key] = REDACTED_VALUE;
      continue;
    }
    result[key] = sanitiseHeapValue(value, depth);
  }
  return result;
}

/**
 * Dispatch a single heap value to the appropriate sanitiser based on its
 * runtime type. Delegate for {@link sanitiseHeapObject}'s value branch.
 *
 * Cyclomatic complexity ≤ 5 (string / array / object / primitive 4-way
 * dispatch + 1 null guard).
 */
function sanitiseHeapValue(value: unknown, depth: number): unknown {
  if (typeof value === "string") {
    return sanitizeHeapString(value);
  }
  if (Array.isArray(value)) {
    return value.map((v) => sanitiseHeapArrayItem(v, depth));
  }
  if (value !== null && typeof value === "object") {
    return sanitiseHeapObject(value as Record<string, unknown>, depth + 1);
  }
  return value;
}

/**
 * Dispatch a single heap array element to the appropriate sanitiser.
 *
 * Cyclomatic complexity ≤ 5 (string / object / primitive 3-way dispatch +
 * 1 null guard).
 */
function sanitiseHeapArrayItem(item: unknown, depth: number): unknown {
  if (typeof item === "string") {
    return sanitizeHeapString(item);
  }
  if (item !== null && typeof item === "object") {
    return sanitiseHeapObject(item as Record<string, unknown>, depth + 1);
  }
  return item;
}

/** Extract the top JS frame for audit emit `details.jsStackTopFrame`. */
function extractJsStackTopFrame(report: Record<string, unknown>): string | null {
  const jsStack = report.javascriptStack as Record<string, unknown> | undefined;
  if (!jsStack || typeof jsStack !== "object") return null;
  const stack = jsStack.stack;
  if (!Array.isArray(stack) || stack.length === 0) return null;
  const top = stack[0];
  return typeof top === "string" ? top : null;
}

/** Extract the top native symbol for audit emit `details.nativeStackTopSymbol`. */
function extractNativeStackTopSymbol(report: Record<string, unknown>): string | null {
  const nativeStack = report.nativeStack;
  if (!Array.isArray(nativeStack) || nativeStack.length === 0) return null;
  const top = nativeStack[0];
  if (typeof top === "string") return top;
  if (top !== null && typeof top === "object") {
    const symbol = (top as Record<string, unknown>).symbol;
    return typeof symbol === "string" ? symbol : null;
  }
  return null;
}

